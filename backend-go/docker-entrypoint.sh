#!/bin/sh
set -e

# Накатываем up-миграции (golang-migrate) перед стартом HTTP-сервера.
# Миграции идемпотентны: повторный старт на актуальной базе — ErrNoChange,
# и entrypoint продолжает работу. При реальной ошибке миграции контейнер
# завершается ненулевым кодом, а не молча стартует на старой схеме.
/out/migrate

# exec — чтобы SIGTERM/SIGINT уходили именно процессу сервера.
exec /out/server
